# 1. Создаем список покупок
shopping_list = ["молоко", "хлеб", "яйца", "сыр", "масло"]
print(f"1. Исходный список: {shopping_list}")

# 2. Добавляем новый элемент в конец списка
shopping_list.append("сок")
print(f"2. После добавления 'сок': {shopping_list}")

# 3. Вставляем элемент на вторую позицию (индекс 1)
shopping_list.insert(1, "йогурт")
print(f"3. После вставки 'йогурт' на позицию 1: {shopping_list}")

# 4. Заменяем "хлеб" на "батон"
index_to_replace = shopping_list.index("хлеб")
shopping_list[index_to_replace] = "батон"
print(f"4. После замены 'хлеб' на 'батон': {shopping_list}")

# 5. Удаляем "масло" из списка
shopping_list.remove("масло")
print(f"5. После удаления 'масло': {shopping_list}")

# 6. Получаем доступ и выводим первый и последний элементы
print(f"6. Первый элемент: {shopping_list[0]}")
print(f"   Последний элемент: {shopping_list[-1]}")

# 7. Используем срез: элементы со второй по четвертую позицию (индексы 1:4)
print(f"7. Срез (элементы 2-4): {shopping_list[1:4]}")

# 8. Сортируем список в алфавитном порядке (на месте)
shopping_list.sort()

# 9. Выводим итоговый список и его длину
print(f"8. Отсортированный список: {shopping_list}")
print(f"9. Длина списка покупок: {len(shopping_list)}")